#!/usr/bin/env python3
"""
Master Lucent-Weight Analysis Pipeline
Runs complete analysis combining weight changes with Lucent feature visualization
"""

import os
import sys

def run_enhanced_visualizations():
    """Generate enhanced weight analysis visualizations"""
    print("🎨 STEP 1: ENHANCED VISUALIZATIONS")
    print("="*50)
    
    sys.path.append('../visualizations')
    from enhanced_visualization import EnhancedVisualizationGenerator
    
    analysis_path = "../../experiments/good_results_weight_analysis/comprehensive_weight_analysis.json"
    
    if not os.path.exists(analysis_path):
        print(f"❌ Weight analysis not found: {analysis_path}")
        print("   Run 'python analyze_good_results.py' first")
        return False
    
    generator = EnhancedVisualizationGenerator(analysis_path)
    generator.generate_all_visualizations()
    
    return True

def run_lucent_integration():
    """Run Lucent-Weight integration analysis"""
    print("\n🔬 STEP 2: LUCENT INTEGRATION")
    print("="*50)
    
    try:
        sys.path.append('../../scripts')
        from lucent_weight_integration import LucentWeightAnalyzer
        from datetime import datetime
        
        # Configuration
        weight_analysis_path = "../../experiments/good_results_weight_analysis/comprehensive_weight_analysis.json"
        
        model_paths = {
            'baseline': '../../experiments/models/resnet50_pretrained.pth',
            'random_forgetting_10percent_RL_conservative': '../../experiments/results/good_results/random_forgetting_10percent_RL_conservative/RLcheckpoint.pth.tar',
            'random_forgetting_20percent_RL_tweak_conservative': '../../experiments/results/good_results/random_forgetting_20percent_RL_tweak_conservative/RLcheckpoint.pth.tar',
            'random_forgetting_30percent_RL_tweak_conservative': '../../experiments/results/good_results/random_forgetting_30percent_RL_tweak_conservative/RLcheckpoint.pth.tar'
        }
        
        # Verify files exist
        if not os.path.exists(weight_analysis_path):
            print(f"❌ Weight analysis not found: {weight_analysis_path}")
            return False
        
        missing_models = [name for name, path in model_paths.items() if not os.path.exists(path)]
        if missing_models:
            print(f"❌ Missing models: {missing_models}")
            return False
        
        # Initialize analyzer
        analyzer = LucentWeightAnalyzer(weight_analysis_path, model_paths)
        
        # Load models
        analyzer.load_models()
        
        # Run comprehensive analysis
        analyzer.generate_comprehensive_report()
        
        return True
        
    except ImportError as e:
        print(f"⚠️  Lucent not available: {e}")
        print("   Install with: pip install lucent")
        return False
    except Exception as e:
        print(f"❌ Error in Lucent integration: {e}")
        return False

